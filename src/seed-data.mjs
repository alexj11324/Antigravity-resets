export function computeStats(resets) {
  const sorted = [...resets].sort(
    (a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime(),
  );
  const gapsDays = [];
  for (let i = 0; i < sorted.length - 1; i++) {
    const diffMs =
      new Date(sorted[i].timestamp).getTime() -
      new Date(sorted[i + 1].timestamp).getTime();
    gapsDays.push(diffMs / (1000 * 60 * 60 * 24));
  }
  const avgIntervalDays =
    gapsDays.length > 0
      ? gapsDays.reduce((acc, n) => acc + n, 0) / gapsDays.length
      : 0;
  const longestWaitDays = gapsDays.length > 0 ? Math.max(...gapsDays) : 0;

  return {
    latest: sorted[0] || null,
    total: sorted.length,
    avgIntervalDays: Number(avgIntervalDays.toFixed(1)),
    longestWaitDays: Number(longestWaitDays.toFixed(1)),
    regularCount: sorted.filter((r) => r.type === "regular").length,
    bankedCount: sorted.filter((r) => r.type === "banked").length,
  };
}
