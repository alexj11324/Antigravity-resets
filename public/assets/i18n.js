export function detectLocale() {
  // The URL is the source of truth. A locale-prefixed path wins, and so does
  // the English root: if / re-rendered itself in the browser's language, that
  // URL would be indexed in a language whose canonical doesn't match, and it
  // would compete with /zh-CN. Switching language navigates to the real path.
  const ssrLang = typeof window !== "undefined" ? window.__SSR_LANG__ : null;
  if (ssrLang && COPY[ssrLang]) return ssrLang;
  // Only reached when the page was opened outside the Worker (a saved local
  // file, a test harness), where no SSR language was injected.
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk") || nav.startsWith("zh-hant")) return "zh-TW";
  if (nav.startsWith("zh")) return "zh-CN";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("ko")) return "ko";
  return "en";
}
